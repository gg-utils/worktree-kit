/**
 * @fileoverview Regression tests for config-driven zsh slot-alias rendering and managed `.zshrc` block installation.
 *
 * This file owns Node `node:test` coverage for `WorktreeStackKit_runZshAliases` render and install actions using temp dirs and synthetic worktree metadata.
 * Flow: seed metadata under a fake worktrees base -> invoke render/install -> assert generated alias script and `.zshrc` splice behavior.
 *
 * @testing Node test: cd packages/worktree-kit && npm run test -- src/zsh-aliases-integration.unit.test.ts
 *
 * @see packages/worktree-kit/src/zsh-aliases-integration.ts - Programmatic entrypoint under test that renders slot aliases from worktree metadata and splices the managed block into `.zshrc`.
 * @see scripts/worktree-stack/integrations/zsh-aliases.ts - Standalone generator script path referenced in assertions and default render config for the alias file header comment.
 * @documentation reviewed=2026-05-23 standard=FILE_OVERVIEW_STANDARDS_TYPESCRIPT@3
 */

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, it } from "node:test";

import {
  WorktreeStackKit_runZshAliases,
  type WorktreeStackKit_ZshAliasesRenderConfig,
} from "./zsh-aliases-integration.js";

const tempDirectories: string[] = [];

const renderConfig: WorktreeStackKit_ZshAliasesRenderConfig = {
  beginMarker: "# >>> project worktree slot aliases >>>",
  endMarker: "# <<< project worktree slot aliases <<<",
  generatorPath: "scripts/worktree-stack/integrations/zsh-aliases.ts",
  messagePrefix: "project",
  shellFunctionPrefix: "project_worktree_slot",
};

function createTempDirectory(prefix: string): string {
  const directoryPath = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  tempDirectories.push(directoryPath);
  return directoryPath;
}

function writeWorktreeMetadata(options: {
  createdAt: string;
  directoryName: string;
  slot: number;
  stackName: string;
  worktreesBase: string;
}): string {
  const worktreePath = path.join(options.worktreesBase, options.directoryName);
  const metadataPath = path.join(
    worktreePath,
    ".tmp",
    "worktree-stack",
    "metadata.json",
  );
  fs.mkdirSync(path.dirname(metadataPath), { recursive: true });
  fs.writeFileSync(
    metadataPath,
    JSON.stringify({
      createdAt: options.createdAt,
      slot: options.slot,
      stackName: options.stackName,
    }),
    "utf8",
  );
  return worktreePath;
}

afterEach(() => {
  for (const directoryPath of tempDirectories.splice(0)) {
    fs.rmSync(directoryPath, { force: true, recursive: true });
  }
});

describe("WorktreeStackKit_runZshAliases", () => {
  it("renders deterministic slot aliases from worktree metadata", () => {
    const tempDirectory = createTempDirectory("worktree-zsh-aliases-");
    const worktreesBase = path.join(tempDirectory, "worktrees");
    const aliasesFile = path.join(tempDirectory, "worktree-slot-aliases.zsh");

    const newerSlotTwoPath = writeWorktreeMetadata({
      createdAt: "2026-03-12T10:00:00.000Z",
      directoryName: "worktree-newer",
      slot: 2,
      stackName: "newer-slot-two",
      worktreesBase,
    });
    writeWorktreeMetadata({
      createdAt: "2026-03-10T10:00:00.000Z",
      directoryName: "worktree-older",
      slot: 2,
      stackName: "older-slot-two",
      worktreesBase,
    });
    const slotFourPath = writeWorktreeMetadata({
      createdAt: "2026-03-11T10:00:00.000Z",
      directoryName: "worktree-four",
      slot: 4,
      stackName: "slot-four",
      worktreesBase,
    });
    const invalidMetadataPath = path.join(
      worktreesBase,
      "worktree-invalid",
      ".tmp",
      "worktree-stack",
      "metadata.json",
    );
    fs.mkdirSync(path.dirname(invalidMetadataPath), { recursive: true });
    fs.writeFileSync(
      invalidMetadataPath,
      JSON.stringify({
        createdAt: "2026-03-09T10:00:00.000Z",
        slot: 0,
        stackName: "invalid",
      }),
      "utf8",
    );

    WorktreeStackKit_runZshAliases({
      action: "render",
      aliasesFile,
      maxSlot: 5,
      quiet: true,
      renderConfig,
      rootDir: "/repo/root",
      worktreesBase,
      zshrcPath: path.join(tempDirectory, ".zshrc"),
    });

    const renderedAliases = fs.readFileSync(aliasesFile, "utf8");

    assert.match(
      renderedAliases,
      /# Generated by scripts\/worktree-stack\/integrations\/zsh-aliases\.ts/u,
    );
    assert.match(renderedAliases, new RegExp(`# Worktrees base: ${worktreesBase}`, "u"));
    assert.match(renderedAliases, /# ap1 \/ ap01 -> unassigned/u);
    assert.match(renderedAliases, /ap1\(\) \{ project_worktree_slot_missing 1; \}/u);
    assert.match(
      renderedAliases,
      new RegExp(`# ap2 / ap02 -> newer-slot-two \\(${newerSlotTwoPath}\\)`, "u"),
    );
    assert.match(
      renderedAliases,
      new RegExp(`ap2\\(\\) \\{ project_worktree_slot_cd '${newerSlotTwoPath}'; \\}`, "u"),
    );
    assert.match(renderedAliases, /ap02\(\) \{ ap2 "\$@"; \}/u);
    assert.doesNotMatch(renderedAliases, /older-slot-two/u);
    assert.match(renderedAliases, /# ap3 \/ ap03 -> unassigned/u);
    assert.match(renderedAliases, /ap3\(\) \{ project_worktree_slot_missing 3; \}/u);
    assert.match(
      renderedAliases,
      new RegExp(`# ap4 / ap04 -> slot-four \\(${slotFourPath}\\)`, "u"),
    );
    assert.match(renderedAliases, /# ap5 \/ ap05 -> unassigned/u);
    assert.match(
      renderedAliases,
      new RegExp(`ap2 / ap02 -> ${newerSlotTwoPath} \\(newer-slot-two\\)`, "u"),
    );
    assert.match(
      renderedAliases,
      new RegExp(`ap4 / ap04 -> ${slotFourPath} \\(slot-four\\)`, "u"),
    );
  });

  it("inserts the managed zshrc block without clobbering unrelated content", () => {
    const tempDirectory = createTempDirectory("worktree-zshrc-insert-");
    const worktreesBase = path.join(tempDirectory, "worktrees");
    const aliasesFile = path.join(tempDirectory, "worktree-slot-aliases.zsh");
    const zshrcPath = path.join(tempDirectory, ".zshrc");

    fs.writeFileSync(
      zshrcPath,
      `export PATH="/usr/local/bin:$PATH"

alias gs='git status'
`,
      "utf8",
    );

    WorktreeStackKit_runZshAliases({
      action: "install",
      aliasesFile,
      maxSlot: 2,
      quiet: true,
      renderConfig,
      rootDir: "/repo/root",
      worktreesBase,
      zshrcPath,
    });

    assert.equal(fs.readFileSync(zshrcPath, "utf8"), `export PATH="/usr/local/bin:$PATH"

alias gs='git status'

# >>> project worktree slot aliases >>>
if [ -f ${JSON.stringify(aliasesFile)} ]; then
  source ${JSON.stringify(aliasesFile)}
fi
# <<< project worktree slot aliases <<<
`);
  });

  it("replaces the managed zshrc block in place and preserves surrounding lines", () => {
    const tempDirectory = createTempDirectory("worktree-zshrc-replace-");
    const worktreesBase = path.join(tempDirectory, "worktrees");
    const aliasesFile = path.join(tempDirectory, "worktree-slot-aliases.zsh");
    const zshrcPath = path.join(tempDirectory, ".zshrc");

    fs.writeFileSync(
      zshrcPath,
      `export PATH="/usr/local/bin:$PATH"

# >>> project worktree slot aliases >>>
if [ -f "/old/aliases.zsh" ]; then
  source "/old/aliases.zsh"
fi
# <<< project worktree slot aliases <<<

alias ga='git add'
`,
      "utf8",
    );

    WorktreeStackKit_runZshAliases({
      action: "install",
      aliasesFile,
      maxSlot: 2,
      quiet: true,
      renderConfig,
      rootDir: "/repo/root",
      worktreesBase,
      zshrcPath,
    });

    assert.equal(fs.readFileSync(zshrcPath, "utf8"), `export PATH="/usr/local/bin:$PATH"

# >>> project worktree slot aliases >>>
if [ -f ${JSON.stringify(aliasesFile)} ]; then
  source ${JSON.stringify(aliasesFile)}
fi
# <<< project worktree slot aliases <<<

alias ga='git add'
`);
  });
});
